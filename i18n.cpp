void loadLang() {
  Preferences p;
  p.begin("tamanaruto", true);  // solo lectura
  uint8_t v = p.getUChar("lang", LANG_DEFAULT);
  p.end();
  gLang = (v < LANG_COUNT) ? (Lang)v : LANG_DEFAULT;
}

void setLang(Lang l) {
  if (l >= LANG_COUNT) return;
  gLang = l;
  Preferences p;
  p.begin("tamanaruto", false);
  p.putUChar("lang", (uint8_t)l);
  p.end();
}
